"""
prompts.py — 双 Agent 的 System Prompt 模板
==========================================
为什么单独放一个文件？
  1. Prompt 是 Agent 的"岗位说明书"，会频繁迭代，独立成文件便于调整；
  2. 提示词工程的核心思想：把业务口径、约束、工具用法写清楚，
     模型才能稳定输出；写得不清楚，模型就会"自由发挥"。

设计原则：
  - Agent 1 只干一件事：自然语言 → 安全 SQL（职责单一，提示词简单可测）；
  - Agent 2 只干一件事：数据 → 业务洞察 + 图表配置（同样单一）；
  - 两段提示词都强约束"只基于给定数据下结论"，对抗模型幻觉。
"""

